// Copies every journal in webapp/journals (<name>/journal_entry.rhai)
// to generated/examples/<name>.rhai, with an index.json listing them, for
// the editor's Examples menu. Also writes generated/fixtures/, the
// repository files the unit tests check against (config/fonts.json, the
// example composite lock file), as modules exporting their text.

import { mkdirSync, readdirSync, copyFileSync, existsSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const journals = join(here, '../../journals');
const out = join(here, '../generated/examples');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const names = readdirSync(journals, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(join(journals, entry.name, 'journal_entry.rhai')))
  .map((entry) => entry.name)
  .sort();
for (const name of names) {
  copyFileSync(join(journals, name, 'journal_entry.rhai'), join(out, `${name}.rhai`));
}
writeFileSync(join(out, 'index.json'), JSON.stringify(names, null, 2) + '\n');
console.log(`examples: ${names.join(', ')}`);

const fixtures = join(here, '../generated/fixtures');
mkdirSync(fixtures, { recursive: true });
const fixture = (name, file) => {
  const text = readFileSync(join(here, '../..', file), 'utf8');
  writeFileSync(join(fixtures, `${name}.ts`), `// ${file}, generated by scripts/examples.mjs.\nexport default ${JSON.stringify(text)};\n`);
};
fixture('fonts-json', 'config/fonts.json');
fixture('shift-vigenere', 'locks/shift_vigenere.rhai');

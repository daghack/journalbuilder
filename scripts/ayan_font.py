def segments(stroke):
	"""Splits a stroke at its corners into runs of points."""
	runs, run = [], []
	for p in stroke:
		if p == "|":
			runs.append(run)
			run = [run[-1]]
		else:
			run.append(p)
	runs.append(run)
	return runs


def path(strokes, f):
	"""The SVG path: each run of points a Catmull-Rom spline as cubics."""
	out = []
	for stroke in strokes:
		first = True
		for run in segments(stroke):
			pts = [f(p) for p in run]
			if first:
				out.append("M %.4f %.4f" % pts[0])
				first = False
			if len(pts) == 2:
				out.append("L %.4f %.4f" % pts[1])
				continue
			ext = [pts[0]] + pts + [pts[-1]]
			for i in range(1, len(ext) - 2):
				p0, p1, p2, p3 = ext[i - 1], ext[i], ext[i + 1], ext[i + 2]
				c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
				c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
				out.append("C %.4f %.4f %.4f %.4f %.4f %.4f" % (c1 + c2 + p2))
	return " ".join(out)


def placed(advance):
	"""Typeface units to glyph units: centred on the advance, y down."""
	return lambda p: ((p[0] - advance / 2) * K, BASELINE - p[1] * K)


LOWER = "abcdefghijklmnopqrstuvwxyz"


def entered_low(strokes):
	"""Whether a glyph's first stroke starts nearer the baseline than the
	x-height."""
	return strokes[0][0][1] < XHEIGHT / 2


def entered_high(strokes):
	"""The glyph with the lower half of its lead-in cut off: its first
	stroke starting where it first comes up to the height the high exits
	(b, o, v, w) leave at, about half the x-height."""
	first = strokes[0]
	top = next(i for i, p in enumerate(first) if p != "|" and p[1] >= 0.5 * XHEIGHT)
	rest = first[top:]
	return [rest] + strokes[1:]


def raw(advance):
	return lambda p: p


